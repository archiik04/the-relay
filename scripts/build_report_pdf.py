"""Build the submission PDF: the write-up (max 2 pages) followed by the required tables.

Sources (edit these, then re-run):
  - docs/REPORT.md : the write-up (a small Markdown subset: #, ##, paragraphs, "- " and "1. " lists,
                     "> " quotes, **bold**, *italic*, `code`)
  - docs/TABLES.md : generated by scripts/analyze_results.py from results/results.csv

Usage: uv run python scripts/build_report_pdf.py   ->  submission/The_Relay_Writeup.pdf
It fails loudly if the write-up part is longer than 2 pages.
"""

import io
import re
import sys
from pathlib import Path

from pypdf import PdfReader
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import cm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (KeepTogether, NextPageTemplate, PageBreak, PageTemplate,
                                Paragraph, Spacer, Table, TableStyle, Frame, BaseDocTemplate)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "submission" / "The_Relay_Writeup.pdf"
MAX_WRITEUP_PAGES = 2
SUBMISSION = ROOT / "submission" / "The_Relay_Submission.pdf"  # write-up + tables + transcript; local only
TRANSCRIPT_MD = ROOT / "submission" / "conversation-history.md"
PAGE_OFFSET = 0  # so appended parts continue the page numbering

ACCENT = colors.HexColor("#1F4E79")
MUTED = colors.HexColor("#555555")
FLAG = colors.HexColor("#B45309")  # placeholders still to fill
RULE = colors.HexColor("#C9D3DD")
HEAD_BG = colors.HexColor("#E8EEF4")


def register_fonts() -> tuple[str, str]:
    fonts = Path("C:/Windows/Fonts")
    try:
        pdfmetrics.registerFont(TTFont("Body", str(fonts / "calibri.ttf")))
        pdfmetrics.registerFont(TTFont("Body-B", str(fonts / "calibrib.ttf")))
        pdfmetrics.registerFont(TTFont("Body-I", str(fonts / "calibrii.ttf")))
        pdfmetrics.registerFont(TTFont("Body-BI", str(fonts / "calibriz.ttf")))
        pdfmetrics.registerFontFamily("Body", normal="Body", bold="Body-B", italic="Body-I", boldItalic="Body-BI")
        mono = "Mono"
        pdfmetrics.registerFont(TTFont(mono, str(fonts / "consola.ttf")))
        return "Body", mono
    except Exception:  # not on Windows: built-in fonts (no arrows / ≤ glyphs)
        return "Helvetica", "Courier"


BODY, MONO = register_fonts()
S = {
    "title": ParagraphStyle("title", fontName=f"{BODY}-B" if BODY == "Body" else "Helvetica-Bold", fontSize=16,
                            leading=19, textColor=ACCENT, spaceAfter=1),
    "sub": ParagraphStyle("sub", fontName=BODY, fontSize=8.5, leading=10.5, textColor=MUTED, spaceAfter=4),
    "h2": ParagraphStyle("h2", fontName=f"{BODY}-B" if BODY == "Body" else "Helvetica-Bold", fontSize=10.6,
                         leading=12.0, textColor=ACCENT, spaceBefore=3.6, spaceAfter=1.2),
    "body": ParagraphStyle("body", fontName=BODY, fontSize=9.0, leading=10.75, alignment=TA_LEFT, spaceAfter=2.2),
    "li": ParagraphStyle("li", fontName=BODY, fontSize=9.0, leading=10.75, spaceAfter=0.6, leftIndent=12,
                         bulletIndent=2, bulletFontName=BODY, bulletFontSize=9.0),
    "quote": ParagraphStyle("quote", fontName=BODY, fontSize=8.9, leading=10.8, leftIndent=8, borderPadding=(3, 4, 3, 5),
                            backColor=colors.HexColor("#F3F5F8"), borderColor=RULE, borderWidth=0.5, spaceBefore=1,
                            spaceAfter=3),
    "cell": ParagraphStyle("cell", fontName=BODY, fontSize=7.6, leading=9.0),
    "cellh": ParagraphStyle("cellh", fontName=f"{BODY}-B" if BODY == "Body" else "Helvetica-Bold", fontSize=7.6,
                            leading=9.0, textColor=ACCENT),
}


def inline(text: str) -> str:
    """Markdown inline -> ReportLab markup."""
    t = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = re.sub(r"`([^`]+)`", lambda m: f'<font face="{MONO}" size="8.3">{m.group(1)}</font>', t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"(?<![\w*])\*([^*\n]+)\*(?![\w*])", r"<i>\1</i>", t)
    # Placeholders stand out so nothing unfinished is submitted by accident.
    t = re.sub(r"\[(ARCHI|TOMORROW)([^\]]*)\]", lambda m: f'<font color="{FLAG.hexval()}"><b>[{m.group(1)}{m.group(2)}]</b></font>', t)
    t = re.sub(r"(github\.com/[\w./-]+)", r'<link href="https://\1" color="#1F4E79">\1</link>', t)
    return t


def parse_markdown(md: str) -> list:
    story: list = []
    lines = md.splitlines()
    i = 0
    first_line = True
    while i < len(lines):
        line = lines[i].rstrip()
        if not line:
            i += 1
            continue
        if line.startswith("# "):
            story.append(Paragraph(inline(line[2:]), S["title"]))
            if i + 1 < len(lines) and lines[i + 1].strip() and not lines[i + 1].startswith("#"):
                story.append(Paragraph(inline(lines[i + 1].strip()), S["sub"]))
                i += 1
            story.append(_rule())
            i += 1
            first_line = False
            continue
        if line.startswith("## "):
            story.append(Paragraph(inline(line[3:]), S["h2"]))
            i += 1
            continue
        if line.startswith("> "):
            buf = []
            while i < len(lines) and lines[i].startswith("> "):
                buf.append(lines[i][2:])
                i += 1
            story.append(Paragraph(inline(" ".join(buf)), S["quote"]))
            continue
        bullet = re.match(r"^(\s*)(- |\d+\. )", line)
        if bullet:
            ordered = bullet.group(2).strip()[0].isdigit()
            items = []
            while i < len(lines) and re.match(r"^(\s*)(- |\d+\. )", lines[i]):
                items.append(re.sub(r"^\s*(- |\d+\. )", "", lines[i]))
                i += 1
            for n, x in enumerate(items, start=1):
                story.append(Paragraph(inline(x), S["li"], bulletText=f"{n}." if ordered else "•"))
            story.append(Spacer(1, 1.6))
            continue
        buf = [line]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r"^(#|> |\s*- |\s*\d+\. )", lines[i]):
            buf.append(lines[i].strip())
            i += 1
        story.append(Paragraph(inline(" ".join(buf)), S["body"]))
        first_line = False
    return story


def _rule():
    t = Table([[""]], colWidths=["100%"], rowHeights=[2])
    t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.8, ACCENT)]))
    return t


def parse_tables(md: str, width: float) -> list:
    """docs/TABLES.md -> titled ReportLab tables (one per '## ' section)."""
    story: list = []
    blocks = re.split(r"^## ", md, flags=re.M)[1:]
    for block in blocks:
        title, *rest = block.splitlines()
        rows = [r for r in rest if r.startswith("|") and not re.match(r"^\|[-| ]+\|$", r)]
        if not rows:
            continue
        cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
        data = [[Paragraph(inline(c), S["cellh"] if ri == 0 else S["cell"]) for c in row] for ri, row in enumerate(cells)]
        ncol = len(cells[0])
        weights = _col_weights(cells)
        col_w = [width * w for w in weights]
        tbl = Table(data, colWidths=col_w, repeatRows=1)
        tbl.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
            ("LINEBELOW", (0, 0), (-1, 0), 0.6, ACCENT),
            ("LINEBELOW", (0, 1), (-1, -1), 0.3, RULE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
            ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ]))
        story.append(KeepTogether([Paragraph(inline(title.strip()), S["h2"]), tbl, Spacer(1, 6)]))
        assert ncol == len(col_w)
    return story


def _col_weights(cells: list[list[str]]) -> list[float]:
    """Column widths proportional to content length (capped), so long text columns get more room."""
    n = len(cells[0])
    lens = [max(min(len(row[j]) if j < len(row) else 0, 60) for row in cells) + 6 for j in range(n)]
    total = sum(lens)
    return [x / total for x in lens]


def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont(BODY, 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawRightString(canvas._pagesize[0] - doc.rightMargin, 0.7 * cm, f"The Relay · page {doc.page + PAGE_OFFSET}")
    canvas.restoreState()


def build(story: list, path, with_tables: list | None = None) -> None:
    doc = BaseDocTemplate(str(path) if not isinstance(path, io.BytesIO) else path, pagesize=A4,
                          leftMargin=1.55 * cm, rightMargin=1.55 * cm, topMargin=1.25 * cm, bottomMargin=1.25 * cm,
                          title="The Relay: write-up", author="Archi Kanungo")
    portrait = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="p", leftPadding=0, rightPadding=0,
                     topPadding=0, bottomPadding=0)
    lw, lh = landscape(A4)
    land = Frame(doc.leftMargin, doc.bottomMargin, lw - doc.leftMargin - doc.rightMargin,
                 lh - doc.topMargin - doc.bottomMargin, id="l", leftPadding=0, rightPadding=0, topPadding=0,
                 bottomPadding=0)
    doc.addPageTemplates([PageTemplate("portrait", [portrait], onPage=footer, pagesize=A4),
                          PageTemplate("landscape", [land], onPage=footer, pagesize=landscape(A4))])
    full = list(story)
    if with_tables:
        full += [NextPageTemplate("landscape"), PageBreak()] + with_tables
    doc.build(full)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    report_md = (ROOT / "docs" / "REPORT.md").read_text(encoding="utf-8")
    buf = io.BytesIO()
    build(parse_markdown(report_md), buf)  # flowables are single-use: parse afresh for every build
    pages = len(PdfReader(io.BytesIO(buf.getvalue())).pages)
    print(f"write-up: {pages} page(s)")
    if pages > MAX_WRITEUP_PAGES:
        raise SystemExit(f"write-up is {pages} pages; the brief allows {MAX_WRITEUP_PAGES}. Cut docs/REPORT.md.")
    tables_md = (ROOT / "docs" / "TABLES.md").read_text(encoding="utf-8")
    intro = [Paragraph("Results tables (required by the brief)", S["title"]), _rule(), Spacer(1, 3)]
    width = landscape(A4)[0] - 2 * 1.55 * cm
    OUT.parent.mkdir(exist_ok=True)
    build(parse_markdown(report_md), OUT, intro + parse_tables(tables_md, width))
    total = len(PdfReader(str(OUT)).pages)
    print(f"{OUT}: {total} pages ({pages} write-up + {total - pages} tables)")
    if TRANSCRIPT_MD.exists():
        attach_transcript(total)


def attach_transcript(first_page: int) -> None:
    """The submission copy: write-up + tables + the conversation history as an appendix (local only)."""
    global PAGE_OFFSET
    from pypdf import PdfWriter
    import build_transcript_pdf as T

    appendix = io.BytesIO()
    PAGE_OFFSET = first_page
    try:
        build(T.story_for(TRANSCRIPT_MD.read_text(encoding="utf-8")), appendix)
    finally:
        PAGE_OFFSET = 0
    w = PdfWriter()
    w.append(str(OUT))
    n = len(w.pages)
    w.append(io.BytesIO(appendix.getvalue()))
    w.add_outline_item("Write-up", 0)
    w.add_outline_item("Results tables", MAX_WRITEUP_PAGES)
    w.add_outline_item("Appendix: conversation history", n)
    w.add_metadata({"/Title": "The Relay: write-up, tables and conversation history", "/Author": "Archi Kanungo"})
    with open(SUBMISSION, "wb") as f:
        w.write(f)
    print(f"{SUBMISSION}: {len(w.pages)} pages (appendix from page {n + 1}; local only, not pushed)")


if __name__ == "__main__":
    main()
